#!/bin/bash
set -e

if [ ! -f /data/safeline/docker-compose.override.yaml ]; then
  printf 'services:\n  postgres:\n    ports:\n      - 127.0.0.1:5432:5432\n' > /data/safeline/docker-compose.override.yaml
fi
if ! ss -tln | grep -q '127.0.0.1:5432'; then
  (cd /data/safeline && docker compose up -d postgres) || true
fi

docker exec safeline-mgt mkdir -p /app/static/ext
docker cp /opt/slext/www/. safeline-mgt:/app/static/ext/

if ! docker exec safeline-mgt grep -q slext-injected /app/static/index.html; then
  docker exec safeline-mgt cat /app/static/index.html > /tmp/slext-index.html
  python3 /opt/slext/bin/patch_index.py /tmp/slext-index.html /tmp/slext-index-patched.html
  docker cp /tmp/slext-index-patched.html safeline-mgt:/app/static/index.html
  rm -f /tmp/slext-index.html /tmp/slext-index-patched.html
  echo "slext-injection-applied"
fi
docker exec safeline-mgt sed -i -E 's|href="/ext/ext\.css(\?v=[0-9]+)?"|href="/ext/ext.css?v=40"|; s|src="/ext/ext\.js(\?v=[0-9]+)?" defer|src="/ext/ext.js?v=40" defer|' /app/static/index.html || true

if ! docker exec safeline-mgt grep -q 'slext-extapi' /etc/nginx/conf.d/default.conf; then
  GW=$(docker network inspect safeline-ce -f '{{(index .IPAM.Config 0).Gateway}}' 2>/dev/null)
  [ -z "$GW" ] && GW=192.168.0.1
  docker exec safeline-mgt cat /etc/nginx/conf.d/default.conf > /tmp/slext-def.conf
  if python3 /opt/slext/bin/patch_mgt_extapi.py /tmp/slext-def.conf /tmp/slext-def-patched.conf "$GW"; then
    docker cp /tmp/slext-def-patched.conf safeline-mgt:/etc/nginx/conf.d/default.conf
    docker exec safeline-mgt nginx -t >/dev/null 2>&1 && docker exec safeline-mgt nginx -s reload || true
    echo "slext-extapi-applied (gw=$GW)"
  fi
  rm -f /tmp/slext-def.conf /tmp/slext-def-patched.conf
fi

LOGCONF=/data/safeline/resources/nginx/conf.d/zz_slext_access_log.conf
if [ ! -f "$LOGCONF" ]; then
  printf 'access_log /var/log/nginx/access.log safeline;\n' > "$LOGCONF"
fi

mkdir -p /data/safeline/resources/nginx/slext-geo /data/safeline/resources/nginx/slext-pages
if [ ! -f /data/safeline/resources/nginx/slext-geo/check.conf ]; then
  printf '# slext geo check (autogenerated)\n' > /data/safeline/resources/nginx/slext-geo/check.conf
fi
if [ ! -f /data/safeline/resources/nginx/conf.d/zz_slext_geo.conf ]; then
  printf '# slext geo (autogenerated)\ngeo $slext_geo_deny {\n    default 0;\n}\n' > /data/safeline/resources/nginx/conf.d/zz_slext_geo.conf
fi
NFMAP=/data/safeline/resources/nginx/conf.d/zz_slext_nf.conf
if [ ! -f "$NFMAP" ] || ! grep -q 'not_found_off' "$NFMAP" 2>/dev/null; then
  printf '# slext 404 page for html navigations\nmap $http_accept $slext_nf_page {\n    default /.safeline/not_found_off;\n    ~*text/html /.safeline/not_found_page;\n}\n' > "$NFMAP"
fi
SKMAP=/data/safeline/resources/nginx/conf.d/zz_slext_skip.conf
if [ ! -f "$SKMAP" ]; then
  printf '# slext skip decryption (pass = safeline key cookie; managed by SLExt)\nmap $http_cookie $slext_skip {\n    default 0;\n    "~*safeline-[0-9a-f]{32,}-key=" 1;\n}\n' > "$SKMAP"
fi
GATE=/data/safeline/resources/nginx/conf.d/zz_slext_gate.conf
if [ ! -f "$GATE" ]; then
  printf '# slext first-visit gate (no document.write for browsers)\nmap "$slext_skip$cookie_nrgpass$http_accept" $slext_gate {\n    default 0;\n    "~^0text/html" 1;\n}\n' > "$GATE"
fi
if [ -f /opt/slext/www/gate.html ]; then
  if ! cmp -s /opt/slext/www/gate.html /data/safeline/resources/nginx/slext-pages/gate.html; then
    cp /opt/slext/www/gate.html /data/safeline/resources/nginx/slext-pages/gate.html
    echo "slext-gate-applied"
  fi
fi
CCMAP=/data/safeline/resources/nginx/conf.d/zz_slext_cc.conf
if [ ! -f "$CCMAP" ] || ! grep -q 'slext_cc' "$CCMAP" 2>/dev/null; then
  printf '# slext no-store for html (avoid caching encrypted pages)\nmap $http_accept $slext_cc {\n    default "";\n    ~*text/html "no-store";\n}\n' > "$CCMAP"
fi

CHANGED=0
for f in /data/safeline/resources/nginx/sites-enabled/IF_*; do
  [ -f "$f" ] || continue
  if [ ! -f "$f.slext-orig" ] && ! grep -q '# slext-' "$f"; then
    cp -a "$f" "$f.slext-orig"
  fi
  if ! grep -q 'access_log /var/log/nginx/access.log safeline' "$f"; then
    sed -i 's|server_name \(.*\);|server_name \1;\n    access_log /var/log/nginx/access.log safeline;|' "$f"
    CHANGED=1
  fi
  if ! grep -q 'slext-geo/check.conf' "$f"; then
    sed -i '/^[[:space:]]*server_name /a\    include /etc/nginx/slext-geo/check.conf;' "$f"
    CHANGED=1
  fi
done

if [ -d /data/safeline/resources/nginx/slext-pages ]; then :; else mkdir -p /data/safeline/resources/nginx/slext-pages; fi
PAGEOUT=$(python3 /opt/slext/bin/patch_site_page.py /data/safeline/resources/nginx/sites-enabled/IF_* 2>/dev/null || true)
case "$PAGEOUT" in
  *'patched files: 0'*) ;;
  *'patched files:'*) CHANGED=1 ;;
esac

if [ "$CHANGED" = "1" ]; then
  if docker exec safeline-tengine nginx -t >/dev/null 2>&1; then
    docker exec safeline-tengine nginx -s reload || true
    echo "slext-sites-applied"
  fi
fi

if [ -f /opt/slext/www/dynamic.css ]; then
  SD=/data/safeline/resources/nginx/safeline-static
  if [ -f "$SD/dynamic.css" ] && [ ! -f "$SD/dynamic.css.orig" ]; then
    cp -a "$SD/dynamic.css" "$SD/dynamic.css.orig" 2>/dev/null || true
  fi
  if ! cmp -s /opt/slext/www/dynamic.css "$SD/dynamic.css"; then
    cp /opt/slext/www/dynamic.css "$SD/dynamic.css"
    echo "slext-dynamic-css-applied"
  fi
fi

if [ -f /opt/slext/www/waiting_first_banner.png ]; then
  CUR=$(docker exec safeline-mgt md5sum /app/static/images/waiting_first_banner.png 2>/dev/null | awk '{print $1}')
  NEW=$(md5sum /opt/slext/www/waiting_first_banner.png | awk '{print $1}')
  if [ -n "$CUR" ] && [ "$CUR" != "$NEW" ]; then
    docker exec safeline-mgt sh -c 'test -f /app/static/images/waiting_first_banner.png.orig || cp /app/static/images/waiting_first_banner.png /app/static/images/waiting_first_banner.png.orig'
    docker cp /opt/slext/www/waiting_first_banner.png safeline-mgt:/app/static/images/waiting_first_banner.png
    echo "slext-wr-banner-applied"
  fi
fi

if [ -f /opt/slext/www/captcha_first_banner.png ]; then
  NEWB=$(md5sum /opt/slext/www/captcha_first_banner.png | awk '{print $1}')
  for f in captcha_first_banner.png captcha_first_banner_en.png; do
    CURB=$(docker exec safeline-mgt md5sum /app/static/images/$f 2>/dev/null | awk '{print $1}')
    if [ -n "$CURB" ] && [ "$CURB" != "$NEWB" ]; then
      docker exec safeline-mgt sh -c "test -f /app/static/images/$f.orig || cp /app/static/images/$f /app/static/images/$f.orig"
      docker cp /opt/slext/www/captcha_first_banner.png safeline-mgt:/app/static/images/$f
      echo "slext-bot-banner-applied($f)"
    fi
  done
fi

if [ -f /opt/slext/www/challenge.css ]; then
  if ! cmp -s /opt/slext/www/challenge.css /data/safeline/resources/nginx/slext-pages/challenge.css; then
    cp /opt/slext/www/challenge.css /data/safeline/resources/nginx/slext-pages/challenge.css
    echo "slext-challenge-css-applied"
  fi
fi
if [ -f /opt/slext/www/auth.css ]; then
  SD2=/data/safeline/resources/nginx/safeline-static
  if [ -f "$SD2/auth.css" ] && [ ! -f "$SD2/auth.css.orig" ]; then
    cp -a "$SD2/auth.css" "$SD2/auth.css.orig" 2>/dev/null || true
  fi
  if ! cmp -s /opt/slext/www/auth.css "$SD2/auth.css"; then
    cp /opt/slext/www/auth.css "$SD2/auth.css"
    echo "slext-auth-css-applied"
  fi
fi

if ! docker exec safeline-mgt sh -c 'sed -n "/location \/assets\/ {/,/^    }/p" /etc/nginx/conf.d/default.conf | grep -q "gzip on;"'; then
  docker exec safeline-mgt sh -c '
    conf=/etc/nginx/conf.d/default.conf
    awk "
    /location \/assets\/ \{/ {
      print
      print \"        gzip on;\"
      print \"        gzip_comp_level 5;\"
      print \"        gzip_types application/javascript text/css application/json image/svg+xml font/ttf font/woff2;\"
      print \"        gzip_vary on;\"
      next
    }
    { print }
    " "'$conf'" > /tmp/def.conf && cat /tmp/def.conf > "'$conf'" && nginx -t >/dev/null 2>&1 && nginx -s reload' || true
  echo "slext-mgt-gzip-applied"
fi
